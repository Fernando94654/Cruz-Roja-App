def emit(tree, title, path):
    lines = ['// Generated by gen_folders.py',
             'digraph folders {',
             f'  graph [rankdir=LR, fontname="Helvetica", nodesep=0.12, ranksep=0.45, pad=0.4, label=<<b>{title}</b>>, labelloc=t, fontsize=22];',
             '  node [shape=box, style="rounded,filled", fontname="Helvetica", fontsize=12, margin="0.15,0.06"];',
             '  edge [color="#999999", arrowhead=none, tailport=e, headport=w];']
    counter = [0]

    def walk(node, depth, parent):
        name, note, children = node
        counter[0] += 1
        nid = f"n{counter[0]}"
        folder = name.endswith("/")
        fill = "#C8102E" if depth == 0 else ("#FDECEE" if folder else "#FFFFFF")
        font = "white" if depth == 0 else "black"
        lines.append(f'  {nid} [label=<<b>{name}</b><br/><font point-size="10">{note}</font>>, fillcolor="{fill}", fontcolor="{font}", color="#C8102E"];')
        if parent:
            lines.append(f'  {parent} -> {nid};')
        for child in children:
            walk(child, depth + 1, nid)

    walk(tree, 0, None)
    lines.append('}')
    open(path, "w").write("\n".join(lines) + "\n")


